type Level = "easy" | "medium" | "hard";
type Table = { columns: string[]; rows: string[][] };

export interface TaskSeed {
  block: string;
  title: string;
  description: string;
  difficulty: Level;
  content: Record<string, unknown>;
}

const LETTERS = ["a", "b", "c", "d"];

// Вариант для шаблона «Выбор ответа»
function choice(
  id: string,
  caseText: string,
  question: string,
  options: string[],
  correct: number,
  explanation: string,
  table?: Table,
) {
  return {
    id,
    case: caseText,
    ...(table ? { table } : {}),
    question,
    options: options.map((text, i) => ({ id: LETTERS[i], text })),
    correct: LETTERS[correct],
    explanation,
  };
}

// Вариант для шаблона «Разметка»: каждое предложение помечено как факт или мнение
function sentences(id: string, items: [string, "fact" | "opinion"][]) {
  return {
    id,
    items: items.map(([text, answer], i) => ({
      id: `s${i + 1}`,
      text,
      answer,
    })),
  };
}

// Вариант для шаблона «Запомни и введи»: несколько карточек, под каждой вопросы
function flash(id: string, rounds: { card: string; q: [string, string][] }[]) {
  return {
    id,
    rounds: rounds.map((r) => ({
      card: r.card,
      showSeconds: 7,
      questions: r.q.map(([label, answer], i) => ({
        id: `q${i + 1}`,
        label,
        answer,
      })),
    })),
  };
}

